// 3.0.2: the website's own styles, scoped to the office screens inside the app (".webui").
// Run before every app build (npm run build does it). Nothing here is downloaded: it reads the website's files.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, "../../..");
const require = createRequire(path.join(web, "package.json"));
const postcss = require("postcss");
const tailwind = require("@tailwindcss/postcss");

const read = (f) => readFileSync(path.join(web, f), "utf8");
const sources = ["app/dashboard", "app/requests", "app/approvals", "app/finance", "app/payment-vouchers", "app/registry", "app/reports", "app/audit-centre", "app/workflow", "app/admin", "app/profile", "app/developer", "app/notifications", "app/components"]
  .map((d) => `@source "${path.join(web, d).replace(/\\/g, "/")}";`).join("\n");
const globals = read("app/globals.css").replace('@import "tailwindcss";', `@import "tailwindcss" source(none);\n${sources}`);
const files = ["app/theme-iet.generated.css", "app/theme-dark.generated.css", "app/theme-dark.css", "app/v4/v4.css", "app/v4/v4-theme.css", "app/v4/v4-select.css", "app/v4/v4-pages.css", "app/v4/v4-brief.css", "app/v4/v4-kit.css", "app/v4/v4-a4-paper.css", "app/v4/v5-skin.css"];

const SCOPE = ".webui";
function scopeSelector(sel) {
  let s = sel.trim();
  if (!s) return s;
  // the website puts its theme on <html> and its root classes on <body class="v4-root">; inside the app both live on .webui
  let lead = "";
  const m = s.match(/^(html(?:\[[^\]]*\]|:not\([^)]*\)|:root)*)\s*(.*)$/);
  if (m && (m[1].length > 4 || /^html\b/.test(s))) { lead = m[1].replace(/:root/g, ""); s = m[2]; }
  s = s.replace(/^:root\b/, "").replace(/^body(\.[\w-]+)*\b/, "").replace(/^\.v4-root\b/, "").trim();
  s = s.replace(/(^|\s)\.v4-root(?=[\s.:[>]|$)/g, "$1").trim();
  const scoped = s ? (s.startsWith(":") || s.startsWith(".v4-ui") && false ? `${SCOPE}${s}` : `${SCOPE} ${s}`) : SCOPE;
  return lead && lead !== "html" ? `${lead} ${scoped}` : scoped;
}
const scope = () => ({
  postcssPlugin: "reqgen-scope",
  Rule(rule) {
    if (rule.__scoped) return;
    const p = rule.parent;
    if (p && p.type === "atrule" && /keyframes/i.test(p.name)) return;
    rule.selectors = rule.selectors.map(scopeSelector);
    rule.__scoped = true;
  },
});
scope.postcss = true;

const tw = await postcss([tailwind({ base: web })]).process(globals, { from: path.join(web, "app/globals.css") });
const all = tw.css + "\n" + files.map((f) => `/* ${f} */\n${read(f)}`).join("\n");
const out = await postcss([scope()]).process(all, { from: undefined });
const banner = "/* GENERATED by scripts/webcss.mjs from the website's styles (scoped to .webui). Do not edit. */\n";
// the owner's rule: no purple anywhere in the app (the names left in old website styles too); no outside addresses
const css = out.css.replace(/purple|violet|fuchsia/gi, "iet-teal").replace(/https?:\/\/tailwindcss\.com/g, "tailwindcss");
writeFileSync(path.join(here, "../src/office/web.css"), banner + css);
console.log("webcss:", Math.round(css.length / 1024), "KB");
